#ifdef OP_PROFILE
// Time profile per TFLM operator on the ESP32-S3 (one core, no INA219). The time of each operator is measured with esp_timer (microseconds)
// through MicroProfilerInterface, averaged over N_REP invocations after N_WARM warm-ups. The input is all zeros (the time does not depend on the values).
#include <Arduino.h>
#include "esp_timer.h"
#include "esp_heap_caps.h"
#include "tensorflow/lite/micro/micro_mutable_op_resolver.h"
#include "tensorflow/lite/micro/micro_interpreter.h"
#include "tensorflow/lite/micro/micro_profiler_interface.h"
#include "tensorflow/lite/schema/schema_generated.h"
namespace tflite { TFLMRegistration Register_TRANSPOSE_CONV_ACT_FIX(); }

#if defined(OP_VARIANT)   // cost-model test (180_/181_): architecture-variation models from include/variant_model.h (generated by 182_), arena in PSRAM
#include "variant_model.h"
#define MODEL_BYTES g_variant_model
#define NAMA VARIANT_NAME
#define PSRAM_ARENA 1
#if VARIANT_FP32
#define IS_FP32 1
#endif
#elif defined(OP_3CH_INT8)
#include "phasenet_3ch_int8_model.h"
#define MODEL_BYTES g_model_3ch_16x8
#define NAMA "3ch_int8"
#define PSRAM_ARENA 1
#elif defined(OP_3CH_16X8)
#include "phasenet_3ch_16x8_model.h"
#define MODEL_BYTES g_model_3ch_16x8
#define NAMA "3ch_16x8"
#define PSRAM_ARENA 1
#elif defined(OP_FP32_1CH)
#include "phasenet_fp32_1ch_model.h"
#define MODEL_BYTES g_model_fp32
#define NAMA "1ch_fp32"
#define PSRAM_ARENA 1
#define IS_FP32 1
#elif defined(OP_FP32_3CH)
#include "phasenet_fp32_3ch_model.h"
#define MODEL_BYTES g_model_fp32
#define NAMA "3ch_fp32"
#define PSRAM_ARENA 1
#define IS_FP32 1
#elif defined(OP_1CH_16X8)
#include "tinyphasenet_16x8_model.h"
#define MODEL_BYTES g_model
#define NAMA "1ch_16x8"
#define PSRAM_ARENA 0
#else
#include "tinyphasenet_int8_model.h"
#define MODEL_BYTES g_model
#define NAMA "1ch_int8"
#define PSRAM_ARENA 0
#endif

#ifndef OP_NWARM
#define OP_NWARM 5
#endif
#ifndef OP_NREP
#define OP_NREP 20
#endif
static const int N_WARM = OP_NWARM, N_REP = OP_NREP, MAXEV = 256;
struct Prof : public tflite::MicroProfilerInterface {
  const char* tag[MAXEV]; int64_t t0[MAXEV]; int64_t dur[MAXEV]; int n = 0;
  uint32_t BeginEvent(const char* t) override { if (n >= MAXEV) return MAXEV - 1; tag[n] = t; t0[n] = esp_timer_get_time(); return n++; }
  void EndEvent(uint32_t h) override { dur[h] = esp_timer_get_time() - t0[h]; }
};
static Prof prof;
static double acc[MAXEV];

void setup() {
  Serial.begin(115200); unsigned long t = millis(); while (!Serial && millis() - t < 3000) delay(10);
  delay(1500);
  const tflite::Model* model = tflite::GetModel(MODEL_BYTES);
  static tflite::MicroMutableOpResolver<14> r;
  r.AddQuantize(); r.AddConv2D(); r.AddDepthwiseConv2D(); r.AddTransposeConv(tflite::Register_TRANSPOSE_CONV_ACT_FIX());
  r.AddReshape(); r.AddExpandDims(); r.AddSqueeze(); r.AddConcatenation(); r.AddSoftmax(); r.AddAdd(); r.AddMul(); r.AddRelu(); r.AddStridedSlice();
  size_t sz; uint8_t* arena;
  if (PSRAM_ARENA) { sz = 4096 * 1024; arena = (uint8_t*)heap_caps_aligned_alloc(16, sz, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT); }
  else { sz = (heap_caps_get_largest_free_block(MALLOC_CAP_INTERNAL | MALLOC_CAP_8BIT) - 24 * 1024) & ~(size_t)15; arena = (uint8_t*)heap_caps_aligned_alloc(16, sz, MALLOC_CAP_INTERNAL | MALLOC_CAP_8BIT); }
  static tflite::MicroInterpreter it(model, r, arena, sz, nullptr, &prof);
  if (it.AllocateTensors() != kTfLiteOk) { Serial.println("OPPROF_ERROR alokasi"); return; }
  TfLiteTensor* in = it.input(0);
  #ifdef IS_FP32
  { uint32_t r = 12345; float* d = (float*)in->data.raw; for (size_t i = 0; i < in->bytes / 4; i++) { r = r * 1664525u + 1013904223u; d[i] = ((r >> 8) / 8388608.0f) - 1.0f; } }
#else
  { uint32_t r = 12345; uint8_t* d = (uint8_t*)in->data.raw; for (size_t i = 0; i < in->bytes; i++) { r = r * 1664525u + 1013904223u; d[i] = (uint8_t)(r >> 24); } }
#endif
  for (int i = 0; i < N_WARM; i++) it.Invoke();
  { TfLiteTensor* o = it.output(0); uint32_t h = 2166136261u; const uint8_t* d = (const uint8_t*)o->data.raw; for (size_t i = 0; i < o->bytes; i++) { h ^= d[i]; h *= 16777619u; } Serial.printf("OPPROF_HASH %08x bytes=%u\n", (unsigned)h, (unsigned)o->bytes); }
  int ne = 0; double tot = 0;
  for (int k = 0; k < N_REP; k++) { prof.n = 0; int64_t a = esp_timer_get_time(); it.Invoke(); tot += (esp_timer_get_time() - a) / 1000.0; ne = prof.n; for (int i = 0; i < ne; i++) acc[i] += prof.dur[i]; }
  Serial.printf("OPPROF_BEGIN %s n_ops=%d n_rep=%d invoke_ms_mean=%.3f\n", NAMA, ne, N_REP, tot / N_REP);
  for (int i = 0; i < ne; i++) Serial.printf("OPPROF %d %s %.1f\n", i, prof.tag[i], acc[i] / N_REP);
  Serial.println("OPPROF_END");
}
void loop() { delay(1000); static int c = 0; if (c++ < 3) { Serial.println("OPPROF_IDLE"); } }
extern "C" void app_main(void) { initArduino(); setup(); while (true) loop(); }
#endif
