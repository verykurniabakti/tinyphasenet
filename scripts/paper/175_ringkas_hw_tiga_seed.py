"""
Step 175 (answer to the advisor, Subsection 3.3): summary of the ESP32-S3 measurements for three seeds (42, 43, 44), six configurations, all with the optimized (fast-path) TRANSPOSE_CONV kernel.
Sources: seed 42 = the session logs of 06-07 Nov already used by 169_ (sesi_06nov_kernel_baru_*, sesi_07nov_float32_fastpath_*); seeds 43 and 44 = firmware/tinyphasenet_profiling/results_hw/sesi_07nov_seed<43|44>_<model>_stead.log (model header and per-seed threshold generated by 163_, 165_, 170_ with the seed argument).
Output: results/final/hw_tiga_seed.json (per seed, mean, sample standard deviation); the summary is printed.
Usage (from this folder): python 175_ringkas_hw_tiga_seed.py
"""
import re, json, statistics as st
D = 'firmware/tinyphasenet_profiling/results_hw/'
V = ['1ch_fp32', '1ch_16x8', '1ch_int8', '3ch_fp32', '3ch_16x8', '3ch_int8']


def hw(path):
    t = open(path, errors='ignore').read().replace('\r', ''); g = lambda p: re.search(p, t)
    if g(r'Latensi Invoke \(Median\)'):
        lat = float(g(r'Latensi Invoke \(Median\)\s*\|\s*([\d.]+)')[1]); ar = float(g(r'Tensor Arena Digunakan\s*\|\s*([\d.]+)')[1]); en = float(g(r'Energi per Inferensi\s*\|\s*([\d.]+)')[1])
        k = g(r'Kesesuaian Keputusan\s*\|\s*(\d+) / (\d+)'); beda, n = int(k[2]) - int(k[1]), int(k[2]); f1 = float(g(r'F1-Score:\s*([\d.]+)')[1])
    else:
        lat = float(g(r'Latensi Invoke \(ms\)\s*\|\s*([\d.]+)')[1]); ar = float(g(r'Tensor arena terpakai \(KB\)\s*\|\s*([\d.]+)')[1]); en = float(g(r'Energi per inferensi \(mJ\)\s*\|\s*([\d.]+)')[1])
        k = g(r'Keputusan berbeda\s*:\s*(\d+) / (\d+)'); beda, n = int(k[1]), int(k[2]); f1 = float(g(r'F1\s+([\d.]+)\s+FPR')[1])
    return dict(latency_ms=lat, arena_kb=ar, energy_mj=en, decisions_diff=beda, decisions_n=n, f1_100=f1)


P42 = {v: (f'sesi_07nov_float32_fastpath_{v[:3]}_stead.log' if v.endswith('fp32') else f'sesi_06nov_kernel_baru_{v}_stead.log') for v in V}
R = {v: {'42': hw(D + P42[v]), '43': hw(D + f'sesi_07nov_seed43_{v}_stead.log'), '44': hw(D + f'sesi_07nov_seed44_{v}_stead.log')} for v in V}
# One-channel Float32: main number = arena in internal SRAM (fits, 203 KB; seeds 42-44, one session per seed); the PSRAM version is stored as 1ch_fp32_psram
R['1ch_fp32_psram'] = R['1ch_fp32']
R['1ch_fp32'] = {sd: hw(D + f'sesi_07nov_seed{sd}_1ch_fp32_sram_stead.log') for sd in ('42', '43', '44')}
for v in ('1ch_fp32_psram',): pass
for v in V + ['1ch_fp32_psram']:
    for key in ('latency_ms', 'energy_mj', 'arena_kb', 'f1_100', 'decisions_diff'):
        xs = [R[v][s][key] for s in ('42', '43', '44')]; R[v].setdefault('rerata', {})[key] = st.mean(xs); R[v].setdefault('sd', {})[key] = st.stdev(xs)
json.dump(R, open('results/final/hw_tiga_seed.json', 'w'), indent=1)
print(f"{'configuration':10s} " + ' | '.join(f'{k:>22s}' for k in ('latency ms (42/43/44; mean±sd)', 'energy mJ', 'arena KB', 'on-board F1 %', 'differing decisions/100')))
for v in V:
    row = []
    for key, nd in (('latency_ms', 1), ('energy_mj', 2), ('arena_kb', 1), ('f1_100', 1), ('decisions_diff', 0)):
        xs = [R[v][s][key] for s in ('42', '43', '44')]; sc = 100 if key == 'f1_100' else 1
        row.append('/'.join(f'{x * sc:.{nd}f}' for x in xs) + f"; {st.mean(xs) * sc:.{nd}f}±{st.stdev(xs) * sc:.{nd}f}")
    print(f'{v:10s} ' + ' | '.join(row))

# ---- per-seed table for Appendix E (Indonesian: decimal comma)
NM = {'1ch_fp32': 'Satu kanal Float32', '1ch_16x8': 'Satu kanal 16x8', '1ch_int8': 'Satu kanal INT8', '3ch_fp32': 'Tiga kanal Float32', '3ch_16x8': 'Tiga kanal 16x8', '3ch_int8': 'Tiga kanal INT8'}
idn = lambda x, nd: f'{x:,.{nd}f}'.replace(',', '§').replace('.', ',').replace('§', '.')   # thousands point, decimal comma
trip = lambda v, key, nd, sc=1: ' / '.join(idn(R[v][s][key] * sc, nd) for s in ('42', '43', '44'))
rows = ''.join(f"{NM[v]} & {trip(v, 'latency_ms', 1)} & {trip(v, 'energy_mj', 1)} & {trip(v, 'f1_100', 1, 100)} & {trip(v, 'decisions_diff', 0)} \\\\\n" for v in V)
open('../jawaban_prof_arief_fase1/tabel_spektrum/tab_hw_per_seed.tex', 'w').write(rows + '\\bottomrule\n')
